#!/bin/bash
# PreToolUse. exit 2 = block, stderr goes to Claude.
in=$(cat); t=$(jq -r .tool_name <<<"$in")
no(){ echo "BLOCKED: $1" >&2; exit 2; }
if [ "$t" = Bash ]; then
  c=$(jq -r '.tool_input.command // ""' <<<"$in")
  grep -qE '(^|[;&|[:space:]/])(adb|emulator|avdmanager)([[:space:]]|$)' <<<"$c" && no "no adb/emulator (ARCHITECTURE §10). Deliver via /ship-apk."
  grep -qE 'gradlew.*([[:space:]:])(test[A-Za-z]*|check|build|connected[A-Za-z]*Test)([[:space:]]|$)' <<<"$c" && no "no unit tests, no build/check (runs tests). Use assembleDebug or compileDebugKotlin."
else
  f=$(jq -r '.tool_input.file_path // .tool_input.notebook_path // ""' <<<"$in")
  case "$f" in
    */tokens.json|*/syllabus_cgl.json) no "generated export. Edit source + run tools/gen_theme.py." ;;
    */core/design/*/Palette.kt) no "generated by tools/gen_theme.py." ;;
    */prototype/*) no "prototype is read-only reference." ;;
    */src/test/*|*/src/androidTest/*) no "no unit tests in this project." ;;
  esac
fi
exit 0
